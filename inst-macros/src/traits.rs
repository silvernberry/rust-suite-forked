/// Converts a syntax path into its compact token representation.
///
/// The generated string removes the whitespace introduced around path
/// separators and generic angle brackets by [`TokenStream::to_string`].
///
/// For example:
///
/// ```ignore
/// Foo < Bar > ::Baz
/// ```
///
/// is converted to:
///
/// ```text
/// Foo<Bar>::Baz
/// ```
fn path_to_string(path: &syn::Path) -> String {
    path.to_token_stream()
        .to_string()
        .replace(" :: ", "::")
        .replace(" < ", "<")
        .replace(" > ", ">")
}

/// Converts a type parameter bound into its normalized string representation.
///
/// Trait bounds are represented from their contained path and normalized using
/// [`path_to_string`]. Lifetime bounds are converted from their token
/// representation with whitespace removed.
///
/// Other bound forms are converted from their token representation and
/// normalized by removing whitespace around path separators and generic
/// angle brackets.
fn type_param_bound_to_string(bound: &syn::TypeParamBound) -> String {
    match bound {
        syn::TypeParamBound::Trait(bound) => 
        {
            let path = &bound.path;
            path_to_string(path)
        } 

        syn::TypeParamBound::Lifetime(lifetime) => {
            lifetime.to_token_stream().to_string().replace(" ", "")
        }

        _ => bound.to_token_stream().to_string().replace(" :: ", "::")
        .replace(" < ", "<")
        .replace(" > ", ">"),
    }
}