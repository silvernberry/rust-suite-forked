/// Transforms instance type associated items declared on an instance trait.
///
/// The transformation validates the instance-specific associated types
/// declared on the trait and dispatches their transformation to the
/// corresponding instance type transformation.
///
/// An associated type may contain either `#[node(...)]` or `#[tuple(...)]`,
/// but not both. Instance node and tuple attributes are only valid on
/// associated type items; using either attribute on an associated constant or
/// function produces an error.
///
/// The transformation also validates references to the containing trait from
/// instance type declarations when invoked in the nested transformation
/// context. Such references are rejected to prevent an instance trait from
/// recursively referring to itself through its generated instance types.
///
/// At least one instance type declaration is required when transforming an
/// instance trait directly. When invoked from a nested transformation, the
/// absence of an instance type declaration is allowed.
///
/// After validation, the transformation delegates the actual generation to:
///
/// - [`ItemTypeNodeInst`] for `#[node(...)]` associated types, including their
///   generated instance node representations and access implementations, and
/// - [`ItemTypeTupleInst`] for `#[tuple(...)]` associated types, including their
///   generated instance tuple representations and access implementations.
///
/// This transformation therefore acts as the entry point for instance
/// associated type processing, while the node and tuple transformations own
/// the generation of their respective representations and access machinery.
#[derive(Debug, Clone)]
struct ItemTypeInst;

type AddonSpace<'a> = (&'a mut File, &'a mut ItemTrait);

impl<'a> Transformation<AddonSpace<'a>, Option<IdentList>> for ItemTypeInst {
    fn raw_transform(&self, transform: &mut AddonSpace<'a>, context: &Option<IdentList>) -> Result<(), proc_macro2::TokenStream> {
        let trait_ = &mut transform.1;

        let node = Inst::node();
        let tuple = Inst::tuple();

        struct VisitIdent {
            exp: Ident,
            found: Option<Ident>
        }

        impl<'ast> Visit<'ast> for VisitIdent {
            fn visit_ident(&mut self, i: &'ast proc_macro2::Ident) {
                if *i == self.exp {
                    self.found = Some(i.clone());
                }
                return 
            }
        }

        let trait_ident = &trait_.ident;
        let mut found = false;

        for item in &trait_.items {
            match item {
                TraitItem::Const(c) => {
                    if let Some(attr) = c.attrs.iter().find(|attr| attr.path().is_ident(&node))
                    {
                        return Err(
                            TraitError::NodeOnlyInTypeAssoc { attr: attr.clone() }.into()
                        );
                    }

                    if let Some(attr) = c.attrs.iter().find(|attr| attr.path().is_ident(&tuple))
                    {
                        return Err(
                            TraitError::TupleOnlyInTypeAssoc { attr: attr.clone() }.into()
                        );
                    }
                }
                TraitItem::Fn(f) => {
                    if let Some(attr) = f.attrs.iter().find(|attr| attr.path().is_ident(&node))
                    {
                        return Err(
                            TraitError::NodeOnlyInTypeAssoc { attr: attr.clone() }.into()
                        );
                    }
                    if let Some(attr) = f.attrs.iter().find(|attr| attr.path().is_ident(&tuple))
                    {
                        return Err(
                            TraitError::TupleOnlyInTypeAssoc { attr: attr.clone() }.into()
                        );
                    }
                }
                TraitItem::Type(t) => {
                    let node = t.attrs.iter().find(|attr| attr.path().is_ident(&Inst::node()));
                    let tuple = t.attrs.iter().find(|attr| attr.path().is_ident(&Inst::tuple()));

                    if node.is_some() && tuple.is_some() {
                        return Err(TraitError::EitherTupleOrNode { attr: tuple.unwrap().clone() } .into())
                    }

                    if node.is_some() || tuple.is_some() {
                        if context.is_some() {
                            let mut visitor = VisitIdent {exp: trait_ident.clone(), found: None};
                            visitor.visit_trait_item_type(&t);
                            if let Some(ident) = visitor.found {
                                return Err(TraitError::InstTraitOverflowReference {ident}.into());
                            }
                        }
                        found = true;
                    }
                }
                _ => {}
            }
        }
        if !found && context.is_none() {
            return Err(TraitError::InstEitherTraitOrNodeOrTuple {}.into());
        }

        ItemTypeNodeInst::checked_transform(&ItemTypeNodeInst, &mut transform.1, &())?;
        ItemTypeTupleInst::checked_transform(&ItemTypeTupleInst, transform, &())?;
        Ok(())
    }

    fn validate_transform(&self, transform: &AddonSpace<'a>, _: Option<&Option<IdentList>>) -> Result<(), proc_macro2::TokenStream> {
        ItemTypeNodeInst::validate_transform(&ItemTypeNodeInst, &transform.1, None)?;
        ItemTypeTupleInst::validate_transform(&ItemTypeTupleInst, transform, None)?;
        Ok(())
    }
}

