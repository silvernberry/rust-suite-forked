/// Visits const generic parameters and replaces `Self` references with the
/// generated holder type.
/// 
/// ```ignore
/// Self -> <holder as trait_path>
/// ```
///
/// The holder represents the concrete trait implementation, while the trait
/// path provides the qualified path used to resolve associated types.
struct ConstParamVisitor<'a> {
    /// The generated holder type.
    holder: &'a Ident,

    /// The trait path used to qualify `Self` references.
    trait_path: &'a Path,
}


impl<'a> VisitMut for ConstParamVisitor<'a> {
    fn visit_type_path_mut(&mut self, ty: &mut syn::TypePath) {
        if ty
            .path
            .segments
            .first()
            .is_some_and(|segment| segment.ident == "Self")
        {
            let holder = self.holder;
            let trait_path = self.trait_path;

            let position = trait_path.segments.len();

            let mut segments = syn::punctuated::Punctuated::new();

            segments.extend(trait_path.segments.iter().cloned());
            segments.extend(ty.path.segments.iter().skip(1).cloned());

            ty.path.segments = segments;

            ty.qself = Some(syn::QSelf {
                lt_token: syn::token::Lt::default(),
                ty: Box::new(syn::parse_quote!(#holder)),
                position,
                as_token: Some(syn::token::As::default()),
                gt_token: syn::token::Gt::default(),
            });

            return;
        }

        visit_mut::visit_type_path_mut(self, ty);
    }
}

/// Transforms instance tuple associated types declared on an instance trait.
///
/// The transformation operates on [`TraitItem::Type`] items containing the
/// `#[tuple(...)]` attribute. Each such associated type declares an instance
/// tuple whose members are exposed as generated instance types.
///
/// For each matching associated type, the transformation:
///
/// - locates and validates the `#[tuple(...)]` attribute,
/// - rejects unsupported associated-type `where` clauses,
/// - extracts the declared associated-type bounds and preserves them for
///   documentation,
/// - replaces the declared bounds with the generated `InstTuple` bound,
/// - extracts the tuple declaration and converts it into instance node
///   arguments,
/// - attaches the generated `#[instance_sub(...)]` attribute,
/// - adds the feature-specific documentation disclaimer,
/// - generates the associated type implementation used as the instance
///   tuple representation, and
/// - generates the instance access implementations for the destructured
///   tuple members.
///
/// For each tuple member, the transformation generates an associated type
/// resolving the member to `Self::Variant`. The member is then passed through
/// the instance access machinery so that it can be resolved as an instance
/// node through the generated access path.
///
/// A documentation-only type alias is also generated for each tuple member
/// when the `inst` feature is disabled. These aliases preserve the visible
/// tuple type and its generic parameters for generated documentation.
///
/// Generates the instance tuple representation together with access
/// implementations for declared tuple types. Under the `inst` feature, those
/// members resolve through the instance tuple implementation; without the
/// feature, the generated aliases provide the corresponding documentation
/// representation.
#[derive(Debug, Clone)]
struct ItemTypeTupleInst;

impl<'a> Transformation<AddonSpace<'a>> for ItemTypeTupleInst {
    fn raw_transform(
        &self,
        transform: &mut AddonSpace<'a>,
        _: &(),
    ) -> Result<(), proc_macro2::TokenStream> {
        let (file, transform) = transform;

        let mut ty_items = Vec::new();
        let tuple = Inst::tuple();
        for item in &mut transform.items {
            if let TraitItem::Type(t) = item {
                if t.attrs.iter().any(|attr| attr.path().is_ident(&tuple)) {
                    ty_items.push(t);
                }
            }
        }

        let mut lt_params: Punctuated<GenericParam, Comma> = Punctuated::new();
        let mut ty_params: Punctuated<GenericParam, Comma> = Punctuated::new();
        let mut ct_params: Punctuated<GenericParam, Comma> = Punctuated::new();
        for param in &transform.generics.params {
            match param {
                GenericParam::Lifetime(lt) => {
                    let mut lt = lt.clone();
                    lt.bounds = Punctuated::new();
                    lt_params.push(GenericParam::Lifetime(lt.clone()));
                },
                GenericParam::Type(ty) => {
                    let mut ty = ty.clone();
                    ty.bounds = Punctuated::new();
                    ty_params.push(GenericParam::Type(ty.clone()));
                },
                GenericParam::Const(c) => {
                    ct_params.push(GenericParam::Const(c.clone()));
                },
            }
        }
        let _ = lt_params.pop_punct();
        let _ = ty_params.pop_punct();
        let _ = ct_params.pop_punct();

        let (_, generic_types, _) = transform.generics.split_for_impl();
        let trait_ident = &transform.ident;

        let support_crate = Inst::support_crate();

        for ty in ty_items {

            if let Some(where_clause) = &ty.generics.where_clause {
                return Err(TraitError::WhereClauseNotSupportInTuple { where_: where_clause.clone() }.into());
            }

            let param_bounds = ty.bounds.clone();
            ty.bounds = Punctuated::new();

            let bounds_len = param_bounds.len();
            let mut param_bounds_docs = Vec::new();
            for (i, bound) in param_bounds.iter().enumerate() {
                param_bounds_docs.push(DocAttr::Ref(type_param_bound_to_string(bound)));
                if i < bounds_len - 1 {
                    param_bounds_docs.push(DocAttr::Raw(" + ".to_string()));
                }
            }

            let trait_bound: TraitBound = parse_quote!(#support_crate::InstTuple<0, Variant: #param_bounds>);
            ty.bounds.push(TypeParamBound::Trait(trait_bound));

            let mut tuple_attr = None;
            let mut build = Vec::new();
            for attr in &ty.attrs {
                if !attr.path().is_ident(&tuple) {
                    build.push(attr.clone());
                    continue;
                }
                if tuple_attr.is_some() {
                    return Err(TraitError::DoubleTuple { attr: attr.clone() }.into());
                };
                tuple_attr = Some(attr.clone());
            }
            ty.attrs = build;
            let Some(tuple_attr) = tuple_attr else {
                return Err(TraitBug::InconsistencyFindingTupleAttribute {}.into());
            };

            let tokens = match &tuple_attr.meta {
                syn::Meta::List(meta_list) => &meta_list.tokens,
                syn::Meta::Path(_) => {
                    return Err(TraitError::TupleRequiresArgs {
                        attr: tuple_attr.clone(),
                    }
                    .into());
                }
                syn::Meta::NameValue(meta) => {
                    return Err(TraitError::TupleRequiresArgsNotValue { meta: meta.clone() }.into());
                }
            };
            if tokens.is_empty() {
                return Err(TraitError::TupleRequiresArgs {
                    attr: tuple_attr.clone(),
                }
                .into());
            }

            let mut indexes = IntList::default();
            indexes.ints.push(LitInt::new("0", Span::call_site()));

            let inst = InstTupleArgs::checked_extract(tokens, &())?;

            let node_args = NodeArgs::checked_extract(&inst.clone().into(), &indexes)?;

            let attrs = &mut ty.attrs;

            let sub_target = Inst::subscriber();
            attrs.insert(0, parse_quote!(#[#sub_target(#node_args)]));

            cfg_feature_disclaimer(ty);

            let assoc_ident = &ty.ident;
            let (_, assoc_generics, _) = &ty.generics.split_for_impl();
            let combined_path: Path = parse_quote!(#trait_ident::#assoc_ident #assoc_generics);
            let holder = format_ident!("T");
            let trait_arg: Path = parse_quote!(#trait_ident #generic_types);

            let mut generics: Punctuated<GenericParam, Comma> = Punctuated::new();
            generics.extend(lt_params.clone());
            generics.push(parse_quote!(#holder: #trait_arg));
            generics.extend(ty_params.clone());
            let mut ct_params = ct_params.clone();
            let mut visitor = ConstParamVisitor {holder: &holder, trait_path: &trait_arg};
            for param in &mut ct_params {
                let GenericParam::Const(c) = param else {
                    unreachable!()
                };
                visitor.visit_const_param_mut(c);
            }
            generics.extend(ct_params);

            let assoc_type: Type = parse_quote!(<#holder as #trait_arg>::#assoc_ident #assoc_generics);
            let addon_impl : ItemImpl = parse_quote!(
                impl<#generics> #assoc_type 
                where 
                    Self: #support_crate::InstTuple<0> 
                {}
            );

            let mut impl_types = Vec::new();
            for tuple in &inst.list {
                let vis = &tuple.visibility;
                let ident = &tuple.ident;

                let mut impl_type: ImplItemType = parse_quote!(#vis type #ident = Self::Variant;);
                impl_type.attrs.push(parse_quote!(#[allow(non_camel_case_types)]));
                impl_type.attrs.push(parse_quote!(#[allow(unused)]));
                impl_type.attrs.push(parse_quote!(#[allow(type_alias_bounds)]));

                let mut doc_type :ItemType = parse_quote!(#vis type #ident<#generics> = #assoc_type;);
                doc_type.attrs.push(parse_quote!(#[allow(non_camel_case_types)]));
                doc_type.attrs.push(parse_quote!(#[allow(unused)]));
                doc_type.attrs.push(parse_quote!(#[allow(type_alias_bounds)]));

                impl_types.push((ident.clone(), impl_type, doc_type));
            }

            for (ident, mut not_doc_ty, mut doc_ty) in impl_types {

                let mut params = Punctuated::new();
                let span = ident.span();
                params.push(crate::args::InstanceIdent::Compile(ident));
                let inst = InstanceModel::Simple(InstanceIdents {span, paren_token: Default::default(), params });

                // Indexes are placeholder, for impl nodes in instances-macro their length is only taken
                let mut indexes = IntList::default();
                for i in 0..InstModelLength::checked_extract(&inst, &())?.0 {
                    indexes
                        .ints
                        .push(LitInt::new(&i.to_string(), Span::call_site()));
                }
                let access = AccessArgsRef(inst);
                let args = access.try_leaf(&indexes).unwrap();

                let mut doc_ty_docs = Vec::new();
                doc_ty_docs.extend( vec![
                    DocAttr::Heading {
                        level: 0,
                        content: vec![
                            DocAttr::Raw(
                                "Instance Tuple Type ".to_string(),
                            ),
                            DocAttr::Ref(path_to_string(&combined_path)),
                        ],
                    },
                    DocAttr::Raw("Implements bounds: ".to_string())
                    ]
                );
                doc_ty_docs.extend(param_bounds_docs.clone());
                doc_ty_docs.extend(vec![
                    DocAttr::LineBreak,
                    DocAttr::Raw(
                        "Destructured Instance Tuple Type with well-defined bounds while used with cfg `--features inst`."
                            .to_string(),
                    ),
                    DocAttr::LineBreak,
                    DocAttr::Raw(
                        "*See* ".to_string(),
                    ),
                    DocAttr::Link {
                        title: "`inst::tuple`".to_string(),
                        url: "inst::tuple".to_string(),
                    },
                    DocAttr::Raw(
                        " *for details.*".to_string(),
                    ),
                    DocAttr::LineBreak,
                ]);
                doc_ty.prepend_docs(doc_ty_docs);
                doc_ty.attrs.insert(0, Inst::not_feature());
                file.items.push(Item::Type(doc_ty));

                cfg_feature_disclaimer(&mut not_doc_ty);
                not_doc_ty.attrs.insert(0, Inst::feature());

                let mut not_doc_version = addon_impl.clone();
                not_doc_version.items.push(syn::ImplItem::Type(not_doc_ty));
                not_doc_version.attrs.push(Inst::feature());
                let access_target = Inst::access_target();
                not_doc_version.attrs.push(parse_quote!(#[#support_crate::#access_target(#args)]));
                Inst::delegate_attribute(&mut not_doc_version.attrs);
                file.items.push(Item::Impl(not_doc_version));

            }

        }

        let attrs = &mut transform.attrs;
        let support_crate = Inst::support_crate();
        let node_target = Inst::node_target();
        attrs.insert(
            0,
            parse_quote!(#[#support_crate::#node_target]),
        );
        Inst::delegate_attribute(attrs);

        Ok(())
    }

    fn validate_transform(
        &self,
        transform: &AddonSpace<'a>,
        context: Option<&()>,
    ) -> Result<(), proc_macro2::TokenStream> {
        let (file, transform) = transform;
        ItemTypeNodeInst::validate_transform(&ItemTypeNodeInst, transform, context)?;

        let support_crate = Inst::support_crate();
        let access_target = Inst::access_target();
        let trait_generics = &transform.generics;
        let (_, generic_types, _) = trait_generics.split_for_impl();
        let trait_ident = &transform.ident;
        let trait_path_seg: PathSegment = parse_quote!(#trait_ident #generic_types);
        let holder = format_ident!("T");
        let holder_index = trait_generics
            .params
            .iter()
            .position(|param| !matches!(param, GenericParam::Lifetime(_)))
            .unwrap_or(trait_generics.params.len());

        let has_type_attrs = |attrs: &Vec<Attribute>| -> Result<(), TokenStream> {
            if !attrs.iter().any(|attr| {
                match &attr.meta {
                    Meta::List(list) => {
                        if !list.path.is_ident("allow") {
                            return false
                        }

                        list.tokens.to_string() == quote!(non_camel_case_types).to_string()
                    }
                    _ => false,
                }
            }) {
                return Err(TraitBug::TraitTupleTargetItemNonCamelCaseAttrMissing {}.into())
            }

            if !attrs.iter().any(|attr| {
                match &attr.meta {
                    Meta::List(list) => {
                        if !list.path.is_ident("allow") {
                            return false
                        }

                        list.tokens.to_string() == quote!(type_alias_bounds).to_string()
                    }
                    _ => false,
                }
            }) {
                return Err(TraitBug::TraitTupleTargetItemTypeAliasBoundsAttrMissing {}.into())
            }

            if !attrs.iter().any(|attr| {
                match &attr.meta {
                    Meta::List(list) => {
                        if !list.path.is_ident("allow") {
                            return false
                        }

                        list.tokens.to_string() == quote!(unused).to_string()
                    }
                    _ => false,
                }
            }) {
                return Err(TraitBug::TraitTupleTargetItemUnusedAttrMissing {}.into())
            }
            Ok(())
        };

        let mut expected_docs = Vec::new();
        for addon in &file.items {
            let impl_ = match addon {
                Item::Impl(impl_) => impl_,
                Item::Type(_) => {
                    continue;
                },
                _ =>  return Err(TraitBug::TraitTupleExpectedAddonNotImplNorTypeAlias {}.into())
            };

            if !impl_.attrs.iter().any(|attr| {
                match &attr.meta {
                    Meta::List(list) => {
                        if !list.path.is_ident("cfg") {
                            return false
                        }

                        list.tokens.to_string() == quote!(feature = "inst").to_string()
                    }
                    _ => false,
                }
            }) {
                return Err(TraitBug::TraitTupleExpectedAddonAccessImplNotFeatureGated {}.into())
            }

            if !impl_.attrs.iter().any(|attr| *attr.path() == parse_quote!(#support_crate::#access_target)) {
                return Err(TraitBug::TraitTupleExpectedAddonAccessImplArgsNotFound {}.into())
            }

            let self_ty = &*impl_.self_ty;

            let Type::Path(path) = &*self_ty else {
                return Err(TraitBug::TraitTupleAddonAccessImplSelfNotTypePath {}.into())
            };

            let Some(qself) = &path.qself else {
                return Err(TraitBug::TraitTupleAddonAccessImplSelfNotAssoc {}.into())
            };

            if qself.as_token.is_none() {
                return Err(TraitBug::TraitTupleAddonAccessImplSelfNotAssoc {}.into())
            }

            if qself.ty != parse_quote!(#holder) {
                return Err(TraitBug::TraitTupleAddonAccessImplSelfAssocQSelfInvalid {}.into())
            }

            let mut segments = path.path.segments.iter();

            let Some(trait_seg) = segments.next() else {
                return Err(TraitBug::TraitTupleAddonAccessImplSelfAssocTraitNotFound {}.into())
            };

            if *trait_seg != trait_path_seg {
                return Err(TraitBug::TraitTupleAddonAccessImplSelfAssocTraitInvalid {}.into())
            }

            let Some(last) = segments.next() else {
                return Err(TraitBug::TraitTupleAddonAccessImplSelfAssocNotFound {}.into())
            };

            if segments.peekable().peek().is_some() {
                return Err(TraitBug::TraitTupleAddonAccessImplSelfInconsistent {}.into())
            }


            if !transform.items.iter().any(|item| {
                let TraitItem::Type(ty) = item else {
                    return false;
                };

                ty.ident == last.ident
            }) {
                return Err(TraitBug::TraitTupleAddonAccessImplForUnknownNode {}.into())
            }

            let generics = &impl_.generics;

            let Some(where_clause) = &generics.where_clause else {
                return Err(TraitBug::TraitTupleAddonAccessImplWhereClauseMissing {}.into())
            };

            if where_clause.predicates.len() > 1 {
                return Err(TraitBug::TraitTupleAddonAccessImplInconsistentWhereClausePreds {}.into())
            }

            let syn::WherePredicate::Type(ty) = &where_clause.predicates[0] else {
                return Err(TraitBug::TraitTupleAddonAccessImplNotTypePred {}.into())
            };

            if ty.bounded_ty != parse_quote!(Self) {
                return Err(TraitBug::TraitTupleAddonAccessImplTypePredNotSelf {}.into())
            }

            if ty.bounds.len() > 1 {
                return Err(TraitBug::TraitTupleAddonAccessImplSelfPredBoundsInconsistent {}.into())
            }

            if ty.bounds[0] != parse_quote!(#support_crate::InstTuple<0>) {
                return Err(TraitBug::TraitTupleAddonAccessImplInvalidSelfInstBound {}.into())
            }

            if generics.params.len() != trait_generics.params.len() + 1 {
                return Err(TraitBug::TraitTupleAddonAccessImplGenericParamsLenInvalid {}.into())
            }

            let Some(holder_param) = generics.params.iter().find_map(|param| {
                if let GenericParam::Type(ty) = param {
                    return Some(ty)
                }
                return None
            }) else {
                return Err(TraitBug::TraitTupleAddonAccessImplHolderGenericParamTypeMissing {}.into())
            };

            if holder_param.ident != holder {
                return Err(TraitBug::TraitTupleAddonAccessImplHolderParamWrongIdent {}.into())
            }

            if holder_param.bounds.len() > 1 {
                return Err(TraitBug::TraitTupleAddonAccessImplHolderParamExtraBounds {}.into())
            }

            let TypeParamBound::Trait(holder_bound) = &holder_param.bounds[0] else {
                return Err(TraitBug::TraitTupleAddonAccessImplHolderParamNotTypeBound {}.into())
            };

            if *holder_bound != parse_quote!(#trait_path_seg) {
                return Err(TraitBug::TraitTupleAddonAccessImplHolderParamBoundInvalid {}.into())
            }

            let mut trait_params_cloned = trait_generics.params.clone();
            trait_params_cloned.insert(holder_index, GenericParam::Type(holder_param.clone()));

            let mut seen = false;
            for (param, t_param) in generics.params.iter().zip(trait_params_cloned) {
                match (param, t_param) {
                    (GenericParam::Lifetime(lt0), GenericParam::Lifetime(lt1)) => {
                        if !lt0.bounds.is_empty() {
                            return Err(TraitBug::TraitTupleAddonAccessImplLifetimeParamHasBounds {}.into())
                        }

                        if lt0.lifetime.ident != lt1.lifetime.ident {
                            return Err(TraitBug::TraitTupleAddonAccessImplLifetimeIdentInvalid {}.into())
                        }
                    },
                    (GenericParam::Type(ty0), GenericParam::Type(ty1)) => {
                        if !seen {
                            seen = true;
                            continue;
                        }
                        if !ty0.bounds.is_empty() {
                            return Err(TraitBug::TraitTupleAddonAccessImplTypeParamHasBounds {}.into())
                        }

                        if ty0.ident != ty1.ident {
                            return Err(TraitBug::TraitTupleAddonAccessImplTypeParamIdentInvalid {}.into())
                        }
                    },
                    (GenericParam::Const(c0), GenericParam::Const(mut c1)) => {
                        let mut visitor = ConstParamVisitor {holder: &holder, trait_path: &parse_quote!(#trait_path_seg)};
                        visitor.visit_const_param_mut(&mut c1);

                        if c0.default != c1.default {
                            return Err(TraitBug::TraitTupleAddonAccessImplConstParamInvalidDefault {}.into())
                        }
                        if c0.ty != c1.ty {
                            return Err(TraitBug::TraitTupleAddonAccessImplConstParamInvalidType {}.into())

                        }
                        if c0.ident != c1.ident {
                            return Err(TraitBug::TraitTupleAddonAccessImplConstParamInvalidIdent {}.into())
                        }
                    },
                    _ => return Err(TraitBug::TraitTupleAddonAccessImplInvalidGenericParam {}.into())
                };
            }

            if impl_.items.len() > 1 {
                return Err(TraitBug::TraitTupleAddonAccessImplExtraItemsFound {}.into())
            }

            let ImplItem::Type(ty) = &impl_.items[0] else {
                return Err(TraitBug::TraitTupleAddonAccessImplItemNotType {}.into())
            };

            let vis = &ty.vis;
            let ident = &ty.ident;

            if ty.ty != parse_quote!(Self::Variant) {
                return Err(TraitBug::TraitTupleAddonAccessImplItemInvalidType {}.into())
            }

            has_type_attrs(&ty.attrs)?;

            expected_docs.push((vis, ident, self_ty.clone()));

        }

        for (vis, ident, self_ty) in expected_docs {
            let Some(ty) = file.items.iter().find_map(|item| {
                let Item::Type(ty) = item else {
                    return None 
                };

                if ty.ident == *ident {
                    return Some(ty)
                }

                return None
            }) else {
                return Err(TraitBug::TraitTupleAddonExpectedDocTypeAliasNotFound {}.into())
            };

            has_type_attrs(&ty.attrs)?;

            if !ty.attrs.iter().any(|attr| {
                match &attr.meta {
                    Meta::List(list) => {
                        if !list.path.is_ident("cfg") {
                            return false
                        }

                        list.tokens.to_string() == quote!(not(feature = "inst")).to_string()
                    }
                    _ => false,
                }
            }) {
                return Err(TraitBug::TraitTupleExpecteDocTypeAliasNotNotFeatureGated {}.into())
            }


            if *ty.ty != self_ty {
                return Err(TraitBug::TraitTupleExpecteDocTypeAliasInvalidType {}.into())
            }

            if ty.vis != *vis {
                return Err(TraitBug::TraitTupleExpecteDocTypeAliasInvalidVisibility {}.into())
            }

            if !ty.attrs.clone().has_docs() {
                return Err(TraitBug::TraitTupleExpecteDocTypeAliasHasNoDocs {}.into())
            }
        }


        Ok(())
    }
}


