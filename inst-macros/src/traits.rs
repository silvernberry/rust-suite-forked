//! Provides the transformation pipeline for instance trait definitions.
//!
//! The module transforms an `#[inst(...)]` trait into its internal expanded
//! representation, including generated instance-counter const generics,
//! instance-node associated types, and instance sum types.
//!
//! The transformation is performed in separate phases for the trait generic
//! header, instance-node and instance-tuple associated types, which are unified by
//! [`TraitInst`]. A documentation-only `cfg(not(feature = "inst"))` representation 
//! is also generated by [`TraitInstDoc`] so the public instance-trait interface can
//! be documented without exposing its internal generated generics.
//!
//! The module also provides the bound and generic-argument helpers used to
//! resolve instance-trait bounds and inject placeholder instance arguments
//! during node transformation.
//!
//! Support-crate delegation is used to invoke the explicit instance-trait and
//! instance-node macro phases after the initial transformations.

