/// Transforms the generic header of an instance trait.
///
/// For every declared instance parameter, this phase inserts a generated
/// `u8` const generic used as the instance counter. The generated counters
/// are inserted after all lifetime parameters and their generic position indexes are
/// recorded in `instance_trait_explicit_target` delegated attribute arguments.
///
/// This phase is independent of the transformation of instance-node
/// associated types. Both transformations are executed as part of the same
/// [`TraitInst`] pipeline.
///
/// Before transformation:
///
/// ```ignore
/// #[inst(Module, Function)]
/// trait Hasher<'a, T> {
///     // ...
/// }
/// ```
///
/// After transformation:
///
/// ```ignore
/// #[instance_trait_explicit_target(2, 3)]
/// trait Hasher<'a, T, const __INST_0: u8, const __INST_1: u8> {
///     // ...
/// }
/// ```
///
/// The indexes `2` and `3` identify the positions of the generated instance
/// counters in the trait's generic parameter list. Existing lifetime
/// parameters remain at the front, while the generated instance counters are
/// inserted before other non-lifetime parameters when applicable.
///
/// The `instance_trait_explicit_target` attribute records the generic indexes,
/// while [`SupportCrate::delegate_attribute`] appends the delegate macro for
/// the final transformation by [`crate::delegate_support_crate_internal_only`].
#[derive(Debug, Clone)]
struct TraitGenericsInst;

impl Transformation<ItemTrait, IdentList> for TraitGenericsInst {
    fn raw_transform(
        &self,
        transform: &mut ItemTrait,
        context: &IdentList,
    ) -> Result<(), proc_macro2::TokenStream> {
        if context.idents.len() > 4 {
            return Err(TraitError::Max4Params {
                idents: context.clone(),
            }
            .into());
        }
        // generic params (for each instance counter)
        let mut collect = Vec::new();
        for (i, _) in context.idents.iter().enumerate() {
            let id_str = i.to_string();
            let id = id_str.as_bytes();
            let ident = gen_const_ident_with_suffix::<TraitInst>(Some(id));
            collect.push(GenericParam::Const(ConstParam {
                attrs: Default::default(),
                const_token: Default::default(),
                ident,
                colon_token: Default::default(),
                ty: parse_quote!(u8),
                eq_token: Default::default(),
                default: Default::default(),
            }));
        }

        let params = &mut transform.generics.params;

        // only append params after lifetimes
        let mut seen_non_lifetime = false;
        for param in params.iter() {
            if let GenericParam::Lifetime(lt) = param {
                if seen_non_lifetime {
                    return Err(ProcParseErr::LifetimeShouldBeDeclaredFront {
                        lt: lt.lifetime.clone(),
                    }
                    .into());
                }
            } else {
                seen_non_lifetime = true;
            }
        }

        let index = params
            .iter()
            .position(|param| !matches!(param, GenericParam::Lifetime(_)))
            .unwrap_or(params.len());

        let mut indexes = Vec::new();
        for (offset, param) in collect.into_iter().enumerate() {
            let offsetted = index + offset;
            params.insert(offsetted, param);
            indexes.push(LitInt::new(&offsetted.to_string(), Span::call_site()));
        }

        let attrs = &mut transform.attrs;

        let support_crate = Inst::support_crate();
        let trait_target = Inst::trait_target();
        attrs.insert(
            0,
            parse_quote!(#[#support_crate::#trait_target(#(#indexes),*)]),
        );
        Inst::delegate_attribute(attrs);

        for item in &mut transform.items {
            let TraitItem::Type(ty) = item else {
                continue;
            };
            if ty.attrs.iter().any(|attr| attr.path().is_ident(&Inst::sum())) {
                cfg_feature_disclaimer(ty);
            }
        }

        Ok(())
    }

    fn validate_transform(
        &self,
        transform: &ItemTrait,
        context: Option<&IdentList>,
    ) -> Result<(), proc_macro2::TokenStream> {
        let support_crate = Inst::support_crate();
        let Some(delegate_macro) = Inst::delegate_macro() else {
            return Err(TraitBug::DelegateMacroNotInitialized {}.into());
        };

        let Some((idx, inst_attr)) = transform.attrs.iter().enumerate().find_map(|(i, attr)| {
            let trait_target = Inst::trait_target();
            if *attr.path() == parse_quote!(#support_crate::#trait_target) {
                return Some((i, attr));
            }
            return None;
        }) else {
            return Err(TraitBug::InstanceTraitMacroNotFound {}.into());
        };

        if !transform.attrs.iter().enumerate().any(|(i, attr)| {
            if i <= idx {
                return false;
            }
            *attr.path() == parse_quote!(#support_crate::#delegate_macro)
        }) {
            return Err(TraitBug::DelegateMacroNotFound {}.into());
        }

        let tokens = match &inst_attr.meta {
            syn::Meta::List(meta_list) => &meta_list.tokens,
            _ => return Err(TraitBug::InstanceTraitMacroArgsNotFound {}.into()),
        };

        let Ok(indexes) = IntList::checked_extract(tokens, &()) else {
            return Err(TraitBug::InstanceTraitMacroIndexesParseFailed {}.into());
        };

        let Some(context) = context else {
            return Ok(());
        };

        let params = &transform.generics.params;
        let mut seen_non_lifetime = false;
        for param in params.iter() {
            if matches!(param, GenericParam::Lifetime(_)) {
                if seen_non_lifetime {
                    return Err(ParseBug::LifetimeShouldBeDeclaredFront {}.into());
                }
            } else {
                seen_non_lifetime = true;
            }
        }
        let mut index = params
            .iter()
            .position(|param| !matches!(param, GenericParam::Lifetime(_)))
            .unwrap_or(params.len());

        let mut collect = Vec::new();
        for (i, _) in context.idents.iter().enumerate() {
            let id_str = i.to_string();
            let id = id_str.as_bytes();
            let ident = gen_const_ident_with_suffix::<TraitInst>(Some(id));
            collect.push((index.clone(), ident));
            index = index + 1;
        }

        if collect.len() != indexes.ints.len() {
            return Err(TraitBug::InstanceTraitMacroIndexesInconsistent {}.into());
        }

        for ((index, ident), int) in collect.into_iter().zip(indexes.ints) {
            if index != parse_pos_usize(&int)? {
                return Err(TraitBug::InstanceCounterIndexInvalid {}.into());
            }

            let Some(param) = params.get(index) else {
                return Err(TraitBug::InstanceCounterConstNotFound {}.into());
            };

            let GenericParam::Const(c) = param else {
                return Err(TraitBug::InstanceCounterGenericNotConst {}.into());
            };

            if c.ident != ident {
                return Err(TraitBug::InstanceCounterGenericInvalidIdent {}.into());
            }

            if c.ty != parse_quote!(u8) {
                return Err(TraitBug::InstanceCounterGenericInvalidType {}.into());
            }
        }

        Ok(())
    }
}

